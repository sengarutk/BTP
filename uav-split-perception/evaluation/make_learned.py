"""Numbers of the paper's learned-bottleneck subsection, from experiments/results/learned_bottleneck/ (30 Oct 2026).

Sources: summary.json (learned_bottleneck.py summary: every payload measured on the same VisDrone2019-DET val frames,
the JPEG size of each learned code's accuracy interpolated on the measured JPEG curve), system.json
(learned_bottleneck_system.py: the paper's policy model over goodput and onboard speed), train_*.json (data sizes).
The pilot configuration (width 64, 12 epochs) is excluded; the family is width 128, 2 decoder layers, 20 epochs.
Writes paper/generated_tables/lb_metrics.tex.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
D = ROOT / "experiments" / "results" / "learned_bottleneck"
OUT = ROOT / "paper" / "generated_tables"
WORDS = {2: "Two", 4: "Four"}


def main():
    s = json.load(open(D / "summary.json"))
    sysm = json.load(open(D / "system.json"))
    fam = [r for r in s["learned"] if r.get("width") == 128 and r.get("dec_layers") == 2]
    assert fam, "no learned configuration of the main family"
    tr = json.load(open(D / f"train_{fam[0]['config']}.json"))
    m = {"LbTrainImages": f"{tr['n_train']:,}".replace(",", "{,}"), "LbHoldImages": str(tr["n_holdout"]),
         "LbValImages": str(fam[0]["n"]), "LbEpochs": str(tr["epochs"]),
         "LbBaseMap": f"{fam[0]['base_map50_95']:.3f}", "LbConfigs": str(len(fam))}
    best = max(fam, key=lambda r: r["map50_95"])
    m["LbMaxMap"], m["LbMaxBytes"] = f"{best['map50_95']:.3f}", f"{best['payload_bytes_mean'] / 1e3:.1f}"
    m["LbMaxCut"] = str(best["cut"])
    m["LbMaxJpegMap"] = "" if best["jpeg_map_at_same_bytes"] is None else f"{best['jpeg_map_at_same_bytes']:.3f}"
    jq90 = next(r for r in s["jpeg"] if r["q"] == 90)
    m["LbJpegNinetyMap"], m["LbJpegNinetyBytes"] = f"{jq90['map50_95']:.3f}", f"{jq90['payload_bytes_mean'] / 1e3:.1f}"
    for cut in sorted({r["cut"] for r in fam}):
        rows = sorted((r for r in fam if r["cut"] == cut), key=lambda r: r["payload_bytes_mean"])
        w = WORDS[cut]
        win = [r for r in rows if r["bytes_saving_vs_jpeg_pct"] is not None and r["bytes_saving_vs_jpeg_pct"] > 0]
        lose = [r for r in rows if r["jpeg_map_at_same_bytes"] is not None and r["map50_95"] < r["jpeg_map_at_same_bytes"]]
        m[f"LbK{w}N"] = str(len(rows))
        if win:
            m[f"LbK{w}SavingMin"] = f"{min(r['bytes_saving_vs_jpeg_pct'] for r in win):.0f}"
            m[f"LbK{w}SavingMax"] = f"{max(r['bytes_saving_vs_jpeg_pct'] for r in win):.0f}"
            m[f"LbK{w}WinMaxBytes"] = f"{max(r['payload_bytes_mean'] for r in win) / 1e3:.1f}"
            ex = max(win, key=lambda r: r["bytes_saving_vs_jpeg_pct"])
            m[f"LbK{w}ExBytes"], m[f"LbK{w}ExMap"] = f"{ex['payload_bytes_mean'] / 1e3:.1f}", f"{ex['map50_95']:.3f}"
            m[f"LbK{w}ExJpegBytes"] = f"{ex['jpeg_bytes_for_same_map'] / 1e3:.1f}"
        if lose:
            lo = min(lose, key=lambda r: r["payload_bytes_mean"])
            m[f"LbK{w}LoseBytes"], m[f"LbK{w}LoseMap"] = f"{lo['payload_bytes_mean'] / 1e3:.1f}", f"{lo['map50_95']:.3f}"
            m[f"LbK{w}LoseJpegMap"] = f"{lo['jpeg_map_at_same_bytes']:.3f}"
    by = sysm["learned_beats_image"]["by_t_full"]
    ts = sorted(by, key=float)
    fast, slow_, pi = ts[0], ts[-2], ts[-1]
    num = lambda x: "0" if x is None else f"{x:.1f}"  # noqa: E731   (the grid is log-spaced: 1 decimal)
    m["LbFastMs"], m["LbFastGoodput"] = f"{float(fast):g}", num(by[fast]["max_goodput_mbps"])
    m["LbSlowMs"], m["LbSlowGoodput"] = f"{float(slow_):g}", num(by[slow_]["max_goodput_mbps"])
    m["LbPiMs"], m["LbPiWins"] = f"{float(pi):.0f}", str(len(by[pi]["goodput_mbps"]))
    m["LbPiGoodput"] = num(by[pi]["max_goodput_mbps"])
    m["LbGridGoodputs"] = str(len(sysm["goodput_mbps"]))
    # where a learned code wins on the Pi: the most any option delivers there (accuracy-weighted on-time results/s)
    pw = [g for g in sysm["grid"] if str(g["t_full_ms"]) == pi and g["goodput_mbps"] in by[pi]["goodput_mbps"]]
    m["LbPiUtilMax"] = f"{max([max(g['learned']['utility'], g['image']['utility']) for g in pw], default=0.0):.1f}"
    g = [v["max_gain_pct_where_image_usable"] for v in by.values() if v["max_gain_pct_where_image_usable"] is not None]
    m["LbMaxGainPct"] = f"{max(g):.0f}" if g else "0"
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "lb_metrics.tex").write_text("% Generated by evaluation/make_learned.py from experiments/results/learned_bottleneck"
                                        " -- do not edit.\n" + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in m.items()))
    for k, v in m.items():
        print(f"{k:22s} {v}")


if __name__ == "__main__":
    main()
