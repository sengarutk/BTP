#!/usr/bin/env python3
"""Energy version of the break-even rule on the Pi 5 (paper 1, roadmap P1-6, 11 Nov 2026).

Proposition prop:be-family compares utilities (accurate results per second). A drone also pays in joules. Per frame,
above the board's idle power and with the Pi's measured constants (hardware/energy/energy_constants.json, pi):
  image q   E_q(B) = e_enc(q) + (a + b B) * 8 b_q / B           encode, then the radio for b_q bytes at goodput B
  split k   E_k(B) = e_c(k)   + (a + b B) * 8 b_k / B           onboard layers 0..k and the encoder, then the radio
with radio power a + b B (W, B in Mbit/s; energy_profile.py's fit), e_c(k) = (s640 inference energy) x (k's edge
fraction of the network's MACs, the convention of the onboard time) + the quantise + zstd time x the inference power,
and e_enc(q) the measured 640-pixel JPEG encode energy (the larger of the two measured qualities, 0.0069 J). At the
accuracy-matched setting q* of Proposition prop:be-family (P A_q >= A_k), with S = 8 (b_q* - b_k) / 1e6 Mbit saved,
the split uses less energy per frame iff
    B < B_E(k) = a S / (e_c(k) - e_enc - b S)        (always, if the denominator is <= 0).
Exact in the model; no fit beyond the measured constants. Also against the JPEG-tuned detector (best of both).
usage: energy_break_even.py      -> experiments/results/break_even/energy_be.json, energy_be_metrics.tex
"""
import json
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))
from evaluation import break_even_rule as b  # noqa: E402
from evaluation.learned_bottleneck_system import family, measured_configs  # noqa: E402
from simulation.system_model import host_full_ms  # noqa: E402

RES = REPO / "experiments" / "results"
OUT = RES / "break_even"


def main():
    c = json.load(open(RES / "hardware" / "energy" / "energy_constants.json"))["pi"]
    a, bb = c["radio_tx_w"]["a"], c["radio_tx_w"]["b_per_mbps"]
    e_full = c["infer_j"]["s640"]
    p_inf = e_full / (c["infer_ms"]["s640"] / 1e3)
    e_enc = max(v for k, v in c["encode_j"].items() if k.startswith("640"))
    pi_full = json.load(open(RES / "hardware" / "placements_summary.json"))["devices"]["pi"]["full_ms"]
    scale = pi_full / host_full_ms(None, b.VD)
    base = measured_configs()
    jpeg = b.jpeg_grid(base)
    codes = b.learned_and_joint() + b.entropy_codes()
    others = [x for x in base if family(x) != "image"] + codes
    best = b.tuned_jpeg(jpeg, b.TUNED_RUNS[0], best=True)
    out = {"constants": {"a_w": a, "b_w_per_mbps": bb, "e_full_j": e_full, "p_inf_w": p_inf, "e_enc_j": e_enc,
                         "host_to_pi_scale": scale}, "method": __doc__.split("\n\n")[1], "rows": []}
    for key, jp in (("untuned", jpeg), ("best_of_both", best)):
        rows, *_ = b.analyse(jp, others)
        byq = {q.name: q for q in jp}
        for r in rows:
            if not r["device"].startswith("Pi") or r["q_star"] is None or r["family"] == "posthoc_split":
                continue
            k = next(x for x in codes if x.name == r["code"])
            q = byq[r["q_star"]]
            e_c = e_full * k.edge_flop_frac + k.host_edge_proc_ms * scale / 1e3 * p_inf
            S = 8 * (q.payload_bytes - k.payload_bytes) / 1e6
            den = e_c - e_enc - bb * S
            be = a * S / den if den > 0 else float("inf")
            out["rows"].append({"detector": key, "code": k.name, "family": r["family"], "q_star": q.name,
                                "code_bytes": k.payload_bytes, "q_star_bytes": q.payload_bytes, "e_compute_j": e_c,
                                "saved_mbit": S, "b_e_mbps": be, "b_be_mbps": r["b_be_mbps"],
                                "e_split_j_at_1mbps": e_c + (a + bb) * 8 * k.payload_bytes / 1e6,
                                "e_image_j_at_1mbps": e_enc + (a + bb) * 8 * q.payload_bytes / 1e6})
    OUT.mkdir(parents=True, exist_ok=True)
    json.dump(out, open(OUT / "energy_be.json", "w"), indent=1)
    m = {}
    for tag, key in (("", "untuned"), ("Tuned", "best_of_both")):
        rs = [r for r in out["rows"] if r["detector"] == key]
        m[f"BeEn{tag}Codes"] = str(len(rs))
        m[f"BeEn{tag}Max"] = f"{1e3 * max(r['b_e_mbps'] for r in rs):.0f}"           # kbit/s
        m[f"BeEn{tag}Median"] = f"{1e3 * float(np.median([r['b_e_mbps'] for r in rs])):.0f}"
        j = next(r for r in rs if r["code"] == "joint_k4_c4_w128_d2")
        m[f"BeEn{tag}JointPi"] = f"{1e3 * j['b_e_mbps']:.0f}"
        m[f"BeEn{tag}JointSplitJ"] = f"{j['e_split_j_at_1mbps']:.2f}"
        m[f"BeEn{tag}JointImageJ"] = f"{j['e_image_j_at_1mbps']:.3f}"
        m[f"BeEn{tag}JointRatio"] = f"{j['e_split_j_at_1mbps'] / j['e_image_j_at_1mbps']:.0f}"
    m["BeEnComputeJ"] = f"{e_full:.2f}"
    m["BeEnEncJ"] = f"{e_enc:.4f}"
    (OUT / "energy_be_metrics.tex").write_text("% Generated by evaluation/energy_break_even.py -- do not edit.\n"
                                               + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in m.items()))
    for k, v in m.items():
        print(k, v)
    for r in sorted(out["rows"], key=lambda r: -r["b_e_mbps"])[:5]:
        print(r["detector"], r["code"], r["q_star"], round(r["e_compute_j"], 3), round(1e3 * r["b_e_mbps"], 1), "kbit/s")


if __name__ == "__main__":
    main()
