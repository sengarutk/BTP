#!/usr/bin/env python3
"""LaTeX macros of the relay-noise sweep for paper 1's journal version (paper/drafts/relay_noise_note.tex):
experiments/results/relay_noise/summary.json -> experiments/results/relay_noise/rn_metrics.tex (prefix Rn).
Paper 2 takes its own numbers from the Pi-calibrated sweep (relay_noise_pi5/) in paper2/make_metrics.py."""
import json
from pathlib import Path

D = Path(__file__).resolve().parent.parent / "experiments" / "results" / "relay_noise"


def main():
    rn = json.load(open(D / "summary.json"))
    hops = rn["setting"]["hops"]
    H = [rn[f"hops{h}"] for h in hops]
    shares = [v["share"] for x in H for v in x["relayed_on_time_adaptive_all"].values() if v["share"] is not None]
    M = {"RnCells": str(sum(x["cells"] for x in H)), "RnSeeds": str(rn["setting"]["seeds"]),
         "RnRankChanges": str(sum(len(x["ranking_changes"]) for x in H)),
         "RnShareClean": f"{100 * H[0]['relayed_on_time_adaptive_all']['3dB_0pct']['share']:.0f}",
         "RnShareMin": f"{100 * min(shares):.0f}",
         "RnLeadMin": f"{min(x['adaptive_lead_fps']['min'] for x in H):.1f}",
         "RnLeadMax": f"{max(x['adaptive_lead_fps']['max'] for x in H):.1f}",
         "RnGainMin": f"{min(x['relay_gain_fps']['adaptive_all_min'] for x in H):.2f}",
         "RnGainMax": f"{max(x['relay_gain_fps']['adaptive_all_max'] for x in H):.2f}"}
    if "second_hop_cost_adaptive_all_fps" in rn:
        M["RnSecondHopMedian"] = f"{rn['second_hop_cost_adaptive_all_fps']['median']:.2f}"
        M["RnSecondHopMin"] = f"{rn['second_hop_cost_adaptive_all_fps']['min']:.2f}"
    tex = "".join(f"\\newcommand{{\\{k}}}{{{v.replace('-', '\\textminus{}') if v.startswith('-') else v}}}\n"
                  for k, v in M.items())
    (D / "rn_metrics.tex").write_text("% Generated by evaluation/relay_noise_macros.py from summary.json -- do not edit.\n"
                                      + tex)
    print(tex)


if __name__ == "__main__":
    main()
