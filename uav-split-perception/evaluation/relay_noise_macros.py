#!/usr/bin/env python3
"""LaTeX macros of the relay-noise sweep for paper 1's journal version (paper/drafts/relay_noise_note.tex):
experiments/results/relay_noise/summary.json -> experiments/results/relay_noise/rn_metrics.tex (prefix Rn).
Paper 2 takes its own numbers from the Pi-calibrated sweep (relay_noise_pi5/) in paper2/make_metrics.py."""
import json
from pathlib import Path

D = Path(__file__).resolve().parent.parent / "experiments" / "results" / "relay_noise"


def main():
    rn = json.load(open(D / "summary.json"))
    hops = rn["setting"]["hops"]
    H = [rn[f"hops{h}"] for h in hops]
    shares = [v["share"] for x in H for v in x["relayed_on_time_adaptive_all"].values() if v["share"] is not None]
    M = {"RnCells": str(sum(x["cells"] for x in H)), "RnSeeds": str(rn["setting"]["seeds"]),
         "RnRankChanges": str(sum(len(x["ranking_changes"]) for x in H)),
         "RnShareClean": f"{100 * H[0]['relayed_on_time_adaptive_all']['3dB_0pct']['share']:.0f}",
         "RnShareMin": f"{100 * min(shares):.0f}", "RnShareMax": f"{100 * max(shares):.0f}",
         "RnGainRelPct": f"{100 * max(x['relay_gain_fps']['adaptive_all_rel_abs_max'] for x in H):.1f}",
         "RnLeadMin": f"{min(x['adaptive_lead_fps']['min'] for x in H):.1f}",
         "RnLeadMax": f"{max(x['adaptive_lead_fps']['max'] for x in H):.1f}",
         "RnGainMin": f"{min(x['relay_gain_fps']['adaptive_all_min'] for x in H):.3f}",
         "RnGainMax": f"{max(x['relay_gain_fps']['adaptive_all_max'] for x in H):.3f}"}
    pcs = [v for x in H for v in x["per_condition_adaptive_all"].values() if v["share_min"] is not None]
    fx1 = H[0]["fixed_split_relayed_frames_on_time"]["blackout_5"]
    fx2 = H[-1]["fixed_split_relayed_frames_on_time"]["blackout_5"]
    M.update({"RnSettings": str(sum(x["settings"] for x in H)),
              "RnCondShareMin": f"{100 * min(v['share_min'] for v in pcs):.0f}",
              "RnCondShareMax": f"{100 * max(v['share_max'] for v in pcs):.0f}",
              "RnNoiseSpreadPts": f"{100 * max(v['share_max'] - v['share_min'] for v in pcs):.0f}",
              "RnRelayedPct": f"{100 * max(x['relayed_per_camera_frame_max'] for x in H):.1f}",
              "RnFixedSent": f"{fx1['3dB_0pct'][0]:.0f}", "RnFixedOnClean": f"{fx1['3dB_0pct'][1]:.0f}",
              "RnFixedOnLoss": f"{max(v[1] for k, v in fx1.items() if k.endswith('_10pct')):.0f}",
              "RnFixedTwoHopMax": f"{max(v[1] for v in fx2.values()):.0f}",
              "RnFixedTwoHopSent": f"{min(v[0] for v in fx2.values()):.0f}",
              "RnFixedGainMin": f"{min(x['fixed_split_relay_gain_fps']['min'] for x in H):.2f}"})
    if "second_hop_cost_adaptive_all_fps" in rn:
        M["RnSecondHopMedian"] = f"{rn['second_hop_cost_adaptive_all_fps']['median']:.4f}"
        M["RnSecondHopMax"] = f"{rn['second_hop_cost_adaptive_all_fps']['max']:.3f}"
        M["RnSecondHopMin"] = f"{rn['second_hop_cost_adaptive_all_fps']['min']:.3f}"
    tex = "".join(f"\\newcommand{{\\{k}}}{{{v.replace('-', '\\textminus{}') if v.startswith('-') else v}}}\n"
                  for k, v in M.items())
    (D / "rn_metrics.tex").write_text("% Generated by evaluation/relay_noise_macros.py from summary.json -- do not edit.\n"
                                      + tex)
    print(tex)


if __name__ == "__main__":
    main()
