#!/usr/bin/env python3
"""Downloads and lays out the evaluation datasets inside ``datasets/``.

COCO val2017 (5,000 held-out images; YOLOv8s was not trained on them) is the primary
accuracy benchmark. COCO128 (the first 128 *training* images) is kept only as a fast smoke test.
VisDrone2019-DET val (548 aerial images) is used by the generalization study; its labels are
mapped onto the COCO classes the pretrained detectors predict (see VISDRONE_TO_COCO).
"""

import argparse
import shutil
import urllib.request
import zipfile
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
DATA = REPO_ROOT / "datasets"
DL = DATA / "coco_dl"
LABELS_URL = "https://github.com/ultralytics/assets/releases/download/v0.0.0/coco2017labels.zip"
IMAGES_URL = "http://images.cocodataset.org/zips/val2017.zip"
COCO128_URL = "https://github.com/ultralytics/assets/releases/download/v0.0.0/coco128.zip"
VISDRONE_URL = "https://github.com/ultralytics/assets/releases/download/v0.0.0/VisDrone2019-DET-val.zip"
# VisDrone category -> COCO class id. 0 = ignored region and 11 = "others" are dropped, as are
# tricycle (7) and awning-tricycle (8), which have no COCO counterpart.
VISDRONE_TO_COCO = {1: 0, 2: 0, 3: 1, 4: 2, 5: 2, 6: 7, 9: 5, 10: 3}


def _download(url: str, dest: Path) -> Path:
    if dest.exists() and dest.stat().st_size > 0:
        return dest
    dest.parent.mkdir(parents=True, exist_ok=True)
    print(f"Downloading {url} -> {dest}")
    tmp = dest.with_suffix(dest.suffix + ".part")
    with urllib.request.urlopen(url, timeout=60) as r, open(tmp, "wb") as f:
        shutil.copyfileobj(r, f)
    tmp.rename(dest)
    return dest


def _coco_names() -> dict:
    from ultralytics.utils import ROOT
    cfg = yaml.safe_load((ROOT / "cfg" / "datasets" / "coco.yaml").read_text())
    return cfg["names"]


def prepare_coco_val2017() -> Path:
    root = DATA / "coco"
    img_dir = root / "images" / "val2017"
    lbl_dir = root / "labels" / "val2017"
    if not (lbl_dir.exists() and any(lbl_dir.iterdir())):
        with zipfile.ZipFile(_download(LABELS_URL, DL / "coco2017labels.zip")) as z:
            members = [m for m in z.namelist() if m.startswith("coco/labels/val2017/") or m == "coco/val2017.txt"]
            z.extractall(DATA, members=members)
    if not (img_dir.exists() and len(list(img_dir.glob("*.jpg"))) == 5000):
        img_dir.parent.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(_download(IMAGES_URL, DL / "val2017.zip")) as z:
            z.extractall(root / "images")
    n_img = len(list(img_dir.glob("*.jpg")))
    if n_img != 5000:
        raise RuntimeError(f"Expected 5000 val2017 images, found {n_img}")
    cfg = DATA / "coco_val2017.yaml"
    cfg.write_text(
        "# COCO 2017 validation split (5,000 images, 80 classes). Generated by scripts/prepare_datasets.py\n"
        + yaml.safe_dump({"path": str(root.resolve()), "train": "images/val2017", "val": "images/val2017", "names": _coco_names()}, sort_keys=False)
    )
    print(f"COCO val2017 ready: {n_img} images -> {cfg.relative_to(REPO_ROOT)}")
    return cfg


def prepare_coco128() -> Path:
    root = DATA / "coco128"
    if not (root / "images" / "train2017").exists():
        with zipfile.ZipFile(_download(COCO128_URL, DL / "coco128.zip")) as z:
            z.extractall(DATA)
    cfg = DATA / "coco128.yaml"
    cfg.write_text(
        "# COCO128: first 128 COCO *train2017* images. Smoke tests only -- not a held-out benchmark.\n"
        + yaml.safe_dump({"path": str(root.resolve()), "train": "images/train2017", "val": "images/train2017", "names": _coco_names()}, sort_keys=False)
    )
    return cfg


def prepare_visdrone_val() -> Path:
    """VisDrone2019-DET val with labels converted to YOLO format and COCO class ids."""
    from PIL import Image

    root = DATA / "visdrone" / "VisDrone2019-DET-val"
    if not (root / "images").exists():
        with zipfile.ZipFile(_download(VISDRONE_URL, DATA / "visdrone" / "VisDrone2019-DET-val.zip")) as z:
            z.extractall(DATA / "visdrone")
    lbl_dir = root / "labels"
    lbl_dir.mkdir(exist_ok=True)
    n_boxes = 0
    for ann in sorted((root / "annotations").glob("*.txt")):
        with Image.open(root / "images" / f"{ann.stem}.jpg") as im:
            w, h = im.size
        lines = []
        for row in ann.read_text().strip().splitlines():
            x, y, bw, bh, score, cat = (int(v) for v in row.split(",")[:6])
            if score == 0 or cat not in VISDRONE_TO_COCO:
                continue
            # Ultralytics discards an image's whole label file if any coordinate is outside [0, 1].
            x0, y0, x1, y1 = max(x, 0), max(y, 0), min(x + bw, w), min(y + bh, h)
            if x1 <= x0 or y1 <= y0:
                continue
            lines.append(f"{VISDRONE_TO_COCO[cat]} {(x0 + x1) / 2 / w:.6f} {(y0 + y1) / 2 / h:.6f} "
                         f"{(x1 - x0) / w:.6f} {(y1 - y0) / h:.6f}")
        (lbl_dir / ann.name).write_text("\n".join(lines) + ("\n" if lines else ""))
        n_boxes += len(lines)
    cfg = DATA / "visdrone_val.yaml"
    cfg.write_text(
        "# VisDrone2019-DET val (548 aerial images), labels mapped to COCO ids. Generated by scripts/prepare_datasets.py\n"
        + yaml.safe_dump({"path": str(root.resolve()), "train": "images", "val": "images", "names": _coco_names()}, sort_keys=False)
    )
    print(f"VisDrone val ready: {len(list((root / 'images').glob('*.jpg')))} images, {n_boxes} boxes -> {cfg.relative_to(REPO_ROOT)}")
    return cfg


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--skip-coco128", action="store_true")
    ap.add_argument("--skip-visdrone", action="store_true")
    args = ap.parse_args()
    prepare_coco_val2017()
    if not args.skip_coco128:
        prepare_coco128()
    if not args.skip_visdrone:
        prepare_visdrone_val()
