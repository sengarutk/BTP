def validate_l1_fidelity() -> bool:
    """Automated L1 Calibration Guard: Compares L1 against empirical 5g_trace_benchmark_results.csv."""
    random.seed(42)
    np.random.seed(42)
    torch.manual_seed(42)
    logger.info("Executing L1 Fidelity Empirical Validation Guard...")
    bench_csv = RESULTS_DIR / "5g_trace_benchmark_results.csv"
    if not bench_csv.exists():
        logger.warning(f"Missing {bench_csv}; skipping L1 guard.")
        return True

    empirical_mean_e2e = 359.05
    empirical_p95_e2e = 493.47

    with open(bench_csv, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for r in reader:
            if r.get("channel_key") == "moderate" and r.get("config_id") == "k4_int8_per_tensor":
                empirical_mean_e2e = float(r["mean_e2e_ms"])
                empirical_p95_e2e = float(r["p95_e2e_ms"])
                break

    # Run L1 single-UAV simulation with calibrated k4-INT8 split
    sim = SwarmSimulationEngine(
        num_uavs=1,
        fidelity="L1",
        cell_capacity_mbps=200.0,
        mobility_model="formation",
        trace_file="trace_5g_moderate.csv",
        duration_s=30.0,
        fps=30.0,
        fixed_cut="k4",
        fixed_dtype="int8",
    )
    res = sim.run_simulation()
    sim_mean_e2e = res["mean_e2e_ms"]
    sim_p95_e2e = res["p95_e2e_ms"]

    # Calculate calibration error %
    error_mean = abs(sim_mean_e2e - empirical_mean_e2e) / empirical_mean_e2e * 100.0
    error_p95 = abs(sim_p95_e2e - empirical_p95_e2e) / empirical_p95_e2e * 100.0

    logger.info(
        f"[L1 Calibration Guard] Empirical Mean: {empirical_mean_e2e:.1f}ms | "
        f"Simulated Mean: {sim_mean_e2e:.1f}ms (Error: {error_mean:.2f}%)"
    )
    logger.info(
        f"[L1 Calibration Guard] Empirical P95: {empirical_p95_e2e:.1f}ms | "
        f"Simulated P95: {sim_p95_e2e:.1f}ms (Error: {error_p95:.2f}%)"
    )

    assert error_mean <= 15.0, f"L1 Mean Latency calibration error ({error_mean:.2f}%) exceeds 15% threshold!"
    assert error_p95 <= 15.0, f"L1 P95 Latency calibration error ({error_p95:.2f}%) exceeds 15% threshold!"
    logger.success("★ L1 Fidelity Calibration Guard PASSED (Error <= 15% tolerance).")
    return True


def run_swarm_benchmarks(
    uav_counts: List[int] = [1, 3, 5, 10, 20],
    duration_s: float = 30.0,
    fidelities: List[str] = ["L1", "L2", "L3", "L4"],
    trace_file: str = "trace_5g_moderate.csv",
    output_dir: Path = RESULTS_DIR,
) -> List[Dict[str, Any]]:
    """Runs parameterized multi-UAV swarm simulation matrix."""
    output_dir.mkdir(parents=True, exist_ok=True)
    random.seed(42)
    np.random.seed(42)
    torch.manual_seed(42)
    all_summaries = []

    logger.info(f"Running Swarm Benchmarks across N={uav_counts}, Fidelities={fidelities}, Duration={duration_s}s, Trace={trace_file}...")

    for fid in fidelities:
        for n in uav_counts:
            # L1 is strictly single-UAV baseline
            if fid == "L1" and n > 1:
                continue

            sim = SwarmSimulationEngine(
                num_uavs=n,
                fidelity=fid,
                cell_capacity_mbps=200.0,
                mobility_model="formation" if fid != "L3" else "rwp",
                trace_file=trace_file,
                duration_s=duration_s,
                fps=30.0,
                fixed_cut="k4" if fid == "L1" else None,
                fixed_dtype="int8" if fid == "L1" else None,
            )
            res = sim.run_simulation()
            all_summaries.append(res)

    # Export JSON
    json_path = output_dir / "swarm_simulation_results.json"
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump({
            "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
            "fidelities": fidelities,
            "uav_counts": uav_counts,
            "duration_s": duration_s,
            "trace_file": trace_file,
            "summaries": all_summaries,
        }, f, indent=2)
    logger.success(f"Exported Swarm Simulation JSON -> {json_path}")

    # Export CSV
    csv_path = output_dir / "swarm_simulation_results.csv"
    csv_headers = [
        "fidelity", "num_uavs", "duration_s", "cell_capacity_mbps", "mobility_model",
        "total_tasks_generated", "total_tasks_delivered", "total_tasks_dropped", "stale_frames_dropped",
        "total_tasks_relayed", "effective_delivery_rate", "delivery_rate_pct", "mean_e2e_ms", "p50_e2e_ms",
        "p95_e2e_ms", "p99_e2e_ms", "mean_tx_ms", "mean_energy_mj"
    ]
    with open(csv_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=csv_headers, extrasaction="ignore")
        writer.writeheader()
        for s in all_summaries:
            writer.writerow(s)
    logger.success(f"Exported Swarm Simulation CSV -> {csv_path}")

    # Print Summary Table
    table_rows = []
    for s in all_summaries:
        table_rows.append([
            s["fidelity"],
            f"{s['num_uavs']} UAVs",
            s["mobility_model"].upper(),
            f"{s['delivery_rate_pct']:.1f}%",
            f"{s['total_tasks_relayed']}",
            f"{s['mean_e2e_ms']:.1f} ms",
            f"{s['p95_e2e_ms']:.1f} ms",
            f"{s['mean_energy_mj']:.1f} mJ",
        ])

    headers = ["Fidelity", "Swarm Size", "Mobility", "Delivery Rate", "Relayed Tasks", "Mean Latency", "P95 Latency", "Mean Energy"]
    print("\n" + "=" * 125)
    print("                    AEGIS-UAV MULTI-UAV SWARM SIMULATION BENCHMARK SUMMARY")
    print("=" * 125)
    print(tabulate(table_rows, headers=headers, tablefmt="fancy_grid"))
    print("=" * 125 + "\n")

    return all_summaries


