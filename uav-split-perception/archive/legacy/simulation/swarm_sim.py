class SwarmMobility:
    """Manages 3D spatial mobility for the UAV swarm."""

    @staticmethod
    def initialize_positions(num_uavs: int, model: str = "formation") -> List[Tuple[np.ndarray, np.ndarray, np.ndarray]]:
        """Initializes positions, velocities, and initial waypoints."""
        configs = []
        if model == "formation":
            # Grid / Line formation moving in positive X direction
            spacing = 50.0  # 50 meters inter-UAV spacing
            cols = max(1, int(math.ceil(math.sqrt(num_uavs))))
            for i in range(num_uavs):
                r = i // cols
                c = i % cols
                pos = np.array([c * spacing, r * spacing, 80.0], dtype=np.float64)
                vel = np.array([10.0, 0.0, 0.0], dtype=np.float64)  # 10 m/s
                waypoint = pos + np.array([2000.0, 0.0, 0.0], dtype=np.float64)
                configs.append((pos, vel, waypoint))
        else:
            # Random Waypoint in 1km x 1km x [50, 150]m airspace
            random.seed(42)
            np.random.seed(42)
            torch.manual_seed(42)
            for _ in range(num_uavs):
                pos = np.array([
                    np.random.uniform(0, 1000.0),
                    np.random.uniform(0, 1000.0),
                    np.random.uniform(50.0, 150.0)
                ], dtype=np.float64)
                wp = np.array([
                    np.random.uniform(0, 1000.0),
                    np.random.uniform(0, 1000.0),
                    np.random.uniform(50.0, 150.0)
                ], dtype=np.float64)
                direction = wp - pos
                norm = np.linalg.norm(direction)
                speed = np.random.uniform(5.0, 15.0)
                vel = (direction / max(norm, 1e-3)) * speed
                configs.append((pos, vel, wp))
        return configs

    @staticmethod
    def step_mobility(uav: UAVState, dt_s: float, model: str = "formation", bounds: float = 1000.0):
        """Advances UAV spatial coordinates."""
        uav.pos += uav.vel * dt_s
        if model == "rwp":
            dist = np.linalg.norm(uav.waypoint - uav.pos)
            if dist < 15.0 or (uav.pos[0] < 0 or uav.pos[0] > bounds or uav.pos[1] < 0 or uav.pos[1] > bounds):
                # Pick new random waypoint
                uav.waypoint = np.array([
                    np.random.uniform(50.0, bounds - 50.0),
                    np.random.uniform(50.0, bounds - 50.0),
                    np.random.uniform(50.0, 150.0)
                ], dtype=np.float64)
                direction = uav.waypoint - uav.pos
                speed = np.random.uniform(5.0, 15.0)
                uav.vel = (direction / max(np.linalg.norm(direction), 1e-3)) * speed


class A2AMeshChannel:
    """802.11ax Wi-Fi 6 A2A Mesh propagation model (5.8 GHz, log-normal shadowing)."""
    
    FREQUENCY_GHZ = 5.8
    N_PATH_LOSS_EXPONENT = 2.2
    SIGMA_SHADOWING_DB = 3.0
    R_MAX_METERS = 350.0
    TX_POWER_DBM = 20.0  # 100 mW
    NOISE_FLOOR_DBM = -95.0

    @classmethod
    def evaluate_mesh_link(cls, pos_a: np.ndarray, pos_b: np.ndarray, payload_bytes: int) -> Dict[str, Any]:
        """
        Calculates 3D Euclidean distance d_ij = ||pos_a - pos_b||_2.
        If d_ij > R_MAX_METERS (350.0m), link is out of range.
        If d_ij <= R_MAX_METERS, evaluates link SNR with path loss exponent n=2.2 and log-normal shadowing sigma=3.0 dB:
            SNR_A2A = P_tx,mesh - PL(d_ij) - N_0
        Computes transmission delay:
            T_mesh = D_wire / R_mesh(SNR_A2A)
        Applies stochastic packet error rate PER_mesh derived from MCS.
        """
        dist = float(np.linalg.norm(pos_a - pos_b))
        if dist > cls.R_MAX_METERS:
            return {
                "in_range": False,
                "dist_m": dist,
                "snr_db": -100.0,
                "rate_mbps": 0.0,
                "t_mesh_ms": 0.0,
                "per": 1.0,
            }

        dist_eff = max(0.1, dist)
        # Free space path loss at 1m: PL(1m) = 20*log10(4*pi*1.0*(f/c))
        pl_1m = 20.0 * math.log10(4.0 * math.pi * 1.0 * (cls.FREQUENCY_GHZ * 1e9) / 3e8)
        shadowing = float(np.random.normal(0, cls.SIGMA_SHADOWING_DB))
        pl_db = pl_1m + 10.0 * cls.N_PATH_LOSS_EXPONENT * math.log10(dist_eff) + shadowing

        rx_power_dbm = cls.TX_POWER_DBM - pl_db
        snr_db = rx_power_dbm - cls.NOISE_FLOOR_DBM

        if snr_db < 5.0:
            rate_mbps = 0.0
            per = 1.0
        elif snr_db < 10.0:
            rate_mbps = 15.0  # MCS 0
            per = 0.05
        elif snr_db < 18.0:
            rate_mbps = 45.0  # MCS 2
            per = 0.02
        elif snr_db < 25.0:
            rate_mbps = 86.7  # MCS 5
            per = 0.005
        else:
            rate_mbps = 144.0  # MCS 8 (802.11ax 20MHz single stream)
            per = 0.001

        d_wire_bits = payload_bytes * 8.0
        if rate_mbps > 0:
            t_mesh_ms = (d_wire_bits / (rate_mbps * 1e6)) * 1000.0
        else:
            t_mesh_ms = 500.0

        return {
            "in_range": True,
            "dist_m": dist,
            "snr_db": snr_db,
            "rate_mbps": rate_mbps,
            "t_mesh_ms": t_mesh_ms,
            "per": per,
        }

    @classmethod
    def compute_link_rate_mbps(cls, pos_a: np.ndarray, pos_b: np.ndarray) -> float:
        res = cls.evaluate_mesh_link(pos_a, pos_b, payload_bytes=0)
        return res["rate_mbps"]
