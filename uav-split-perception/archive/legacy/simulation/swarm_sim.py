class SwarmSimulationEngine:
    """Core Discrete-Event Multi-UAV Swarm Perception Simulator."""

    def __init__(
        self,
        num_uavs: int = 5,
        fidelity: str = "L4",
        cell_capacity_mbps: float = 200.0,
        mobility_model: str = "formation",
        trace_file: str = "trace_5g_moderate.csv",
        duration_s: float = 120.0,
        fps: float = 30.0,
        fixed_cut: Optional[str] = None,
        fixed_dtype: Optional[str] = None,
    ):
        self.num_uavs = num_uavs
        self.fidelity = fidelity  # L1, L2, L3, L4
        self.cell_capacity_mbps = cell_capacity_mbps
        self.mobility_model = mobility_model
        self.trace_file = trace_file
        self.duration_s = duration_s
        self.fps = fps
        self.task_interval_s = 1.0 / fps
        self.fixed_cut = fixed_cut
        self.fixed_dtype = fixed_dtype

        # Load calibration artifacts
        self.compute_costs, self.payload_sizes, self.energy_params, self.map_table = load_calibration_data()

        # Load 5G channel trace
        self.trace_records = self._load_trace(trace_file)
        self.trace_len = len(self.trace_records)

        # Initialize UAV Swarm Nodes
        mobility_inits = SwarmMobility.initialize_positions(num_uavs, mobility_model)
        self.uavs: List[UAVState] = []
        for i in range(num_uavs):
            pos, vel, wp = mobility_inits[i]
            cut = self.fixed_cut if self.fixed_cut else "k4"
            dtype = self.fixed_dtype if self.fixed_dtype else "int8"
            self.uavs.append(UAVState(
                uav_id=i,
                pos=pos,
                vel=vel,
                waypoint=wp,
                battery_wh=self.energy_params.get("battery_capacity_wh", 55.5),
                shaper=UserSpaceRateLimiter(max_queue_depth=30),
                current_cut=cut,
                current_dtype=dtype,
            ))

        # Completed tasks log
        self.completed_tasks: List[PerceptionTask] = []
        self.relayed_tasks_count = 0

    def _load_trace(self, trace_file: str) -> List[Dict[str, float]]:
        """Loads and standardizes 100 Hz CSV channel trace."""
        trace_path = TRACES_DIR / trace_file if not Path(trace_file).exists() else Path(trace_file)
        if not trace_path.exists():
            from simulation.trace_generator import generate_all_traces
            generate_all_traces()

        records = []
        with open(trace_path, "r", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            for row in reader:
                records.append({
                    "timestamp_ms": float(row["timestamp_ms"]),
                    "bandwidth_mbps": max(0.0, float(row["bandwidth_mbps"])),
                    "delay_ms": max(0.0, float(row["delay_ms"])),
                    "loss_pct": max(0.0, float(row["packet_loss_pct"])),
                    "sinr_db": float(row.get("sinr_db", 15.0)),
                })
        return records

    def _get_channel_state(self, uav_id: int, sim_time_s: float) -> Dict[str, float]:
        """Returns 5G channel telemetry for a specific UAV at current simulation time."""
        # Apply slight temporal phase offset across UAVs in multi-UAV mode
        offset = (uav_id * 150) if self.fidelity != "L1" else 0
        sample_idx = int(sim_time_s * 100.0 + offset) % self.trace_len
        return self.trace_records[sample_idx]

    def _evaluate_dynamic_policy(self, uav: UAVState, bw_mbps: float, sim_time_s: float):
        """Multi-objective split optimization J_i(k, dtype, B_i) with continuous penalty & hysteresis."""
        if self.fixed_cut is not None:
            uav.current_cut = self.fixed_cut
            uav.current_dtype = self.fixed_dtype if self.fixed_dtype else "int8"
            return

        if sim_time_s - uav.last_policy_eval_s < 0.20:  # 200 ms evaluation epoch
            return

        uav.last_policy_eval_s = sim_time_s

        candidates = [
            {"cut": "k4", "dtype": "int8", "cut_k": 4, "flop_pct": 21.38, "quant_ms": 0.28, "cloud_ms": 5.0},
            {"cut": "k4", "dtype": "fp16", "cut_k": 4, "flop_pct": 21.38, "quant_ms": 0.15, "cloud_ms": 5.0},
            {"cut": "k9", "dtype": "int8", "cut_k": 9, "flop_pct": 43.66, "quant_ms": 0.52, "cloud_ms": 3.6},
            {"cut": "k9", "dtype": "fp16", "cut_k": 9, "flop_pct": 43.66, "quant_ms": 0.28, "cloud_ms": 3.6},
            {"cut": "full", "dtype": "fp32", "cut_k": 22, "flop_pct": 100.0, "quant_ms": 0.0, "cloud_ms": 0.0},
        ]

        best_cand = candidates[0]
        best_cost = float("inf")
        alpha, beta, gamma = 0.40, 0.40, 0.20
        E_max = 2000.0
        T_max = 300.0
        T_deadline = 300.0
        map_base = 0.7594
        EDGE_FULL_LATENCY_MS = 180.0  # Embedded Jetson Nano full inference calibration

        for cand in candidates:
            cut_k = str(cand["cut_k"])
            dtype = cand["dtype"]
            key = f"k{cut_k}_{dtype}" if cand["cut_k"] < 22 else "full_fp32"

            p_size = self.payload_sizes.get(key, {"wire_bytes": 0, "wire_bits": 0})

            if cand["cut"] == "full":
                t_edge = EDGE_FULL_LATENCY_MS
                t_cloud = 0.0
                t_tx = 0.0
            else:
                t_edge = EDGE_FULL_LATENCY_MS * (cand["flop_pct"] / 100.0) + cand["quant_ms"]
                t_cloud = cand["cloud_ms"]
                payload_bits = p_size.get("wire_bits", 0)
                if bw_mbps <= 0.01:
                    t_tx = 500.0
                else:
                    t_tx = (payload_bits / (bw_mbps * 1e6)) * 1000.0

            # Estimate queuing serialization delay
            t_queue = (uav.shaper.queue_depth * p_size.get("wire_bits", 0) / max(0.01, bw_mbps * 1e6)) * 1000.0 if cand["cut"] != "full" else 0.0
            t_total = t_edge + t_tx + t_queue + t_cloud
            e_uav = 11.233 * t_edge + 3.80 * t_tx

            # Accuracy
            matching_map = next((m for m in self.map_table if m["cut_layer"] == cand["cut_k"] and m["dtype"] == dtype), None)
            map_val = matching_map["map_50"] if matching_map else map_base

            # Deadline penalty
            penalty = 5.0 * ((t_total - T_deadline) / T_deadline) ** 2 if t_total > T_deadline else 0.0

            cost = (
                alpha * (e_uav / E_max)
                + beta * (t_total / T_max)
                + gamma * (1.0 - (map_val / map_base))
                + penalty
            )

            if cost < best_cost:
                best_cost = cost
                best_cand = cand

        uav.current_cut = best_cand["cut"]
        uav.current_dtype = best_cand["dtype"]
    def _execute_second_price_auction(self, requesting_uav: UAVState, sim_time_s: float) -> Optional[int]:
        """Conducts collaborative Second-Price Reverse Auction for A2A Wi-Fi relaying."""
        bids = []
        w1, w2, w3 = 0.40, 0.40, 0.20
        R_max = A2AMeshChannel.R_MAX_METERS
        bat_max = self.energy_params.get("battery_capacity_wh", 55.5)

        for other in self.uavs:
            if other.uav_id == requesting_uav.uav_id:
                continue

            dist = float(np.linalg.norm(requesting_uav.pos - other.pos))
            if dist <= R_max:
                ch_other = self._get_channel_state(other.uav_id, sim_time_s)
                # Candidate peer must have strong cellular link (> 15 Mbps) and queue capacity
                if ch_other["bandwidth_mbps"] >= 15.0 and ch_other["loss_pct"] < 10.0 and other.shaper.queue_depth < other.shaper.max_queue_depth:
                    cost_ij = (
                        w1 * (dist / R_max)
                        + w2 * (other.shaper.queue_depth / other.shaper.max_queue_depth)
                        + w3 * (1.0 - (other.battery_wh / bat_max))
                    )
                    bids.append((cost_ij, other.uav_id))

        if not bids:
            return None

        # Lowest cost peer wins reverse auction
        bids.sort(key=lambda x: x[0])
        winner_uav_id = bids[0][1]
        return winner_uav_id

    def run_simulation(self) -> Dict[str, Any]:
        """Executes full discrete-event simulation timeline with accurate rate limiting and contention."""
        # Task 4.3: Deterministic global seeding at start of simulation pass
        random.seed(42)
        np.random.seed(42)
        torch.manual_seed(42)

        sim_time = 0.0
        dt_step = self.task_interval_s  # Process frame arrivals at FPS rate
        global_task_counter = 0

        logger.info(
            f"Starting Swarm Simulation [Fidelity: {self.fidelity}, UAVs: {self.num_uavs}, "
            f"Cell Cap: {self.cell_capacity_mbps} Mbps, Duration: {self.duration_s}s, Mobility: {self.mobility_model}]..."
        )

        while sim_time < self.duration_s:
            # 1. Mobility Updates (L3 / L4)
            if self.fidelity in ["L3", "L4"]:
                for uav in self.uavs:
                    SwarmMobility.step_mobility(uav, dt_step, self.mobility_model)

            # 2. Channel States & Shared Contention
            ch_states = [self._get_channel_state(u.uav_id, sim_time) for u in self.uavs]
            
            # Count active offloading UAVs
            active_tx_count = max(1, sum(1 for u in self.uavs if u.current_cut != "full"))
            
            if self.fidelity == "L1" or self.num_uavs <= 1:
                bw_allocated = [ch["bandwidth_mbps"] for ch in ch_states]
            else:
                fair_share_mbps = self.cell_capacity_mbps / max(1, active_tx_count)
                bw_allocated = [min(ch["bandwidth_mbps"], fair_share_mbps) for ch in ch_states]

            # 3. Dynamic Policy Optimization
            for idx, uav in enumerate(self.uavs):
                eff_bw = bw_allocated[idx]
                if self.fidelity != "L1" or self.fixed_cut is None:
                    self._evaluate_dynamic_policy(uav, eff_bw, sim_time)

            # 4. Generate and Process Tasks for Each UAV
            for idx, uav in enumerate(self.uavs):
                global_task_counter += 1
                uav.tasks_generated += 1

                cut = uav.current_cut
                dtype = uav.current_dtype
                key = f"{cut}_{dtype}" if cut != "full" else "full_fp32"
                p_info = self.payload_sizes.get(key, {"wire_bytes": 0, "wire_bits": 0})
                payload_bytes = p_info["wire_bytes"]
                
                ch_info = ch_states[idx]
                alloc_bw = bw_allocated[idx]

                relayed_via = None
                t_mesh_ms = 0.0
                per_mesh = 0.0

                # L4 Collaborative Reverse Auction
                if self.fidelity == "L4" and cut != "full":
                    # Estimate delay
                    t_est_tx = (payload_bytes * 8) / max(0.01, alloc_bw * 1e6) * 1000.0
                    t_est_total = t_est_tx + uav.shaper.queue_depth * 33.3

                    if ch_info["bandwidth_mbps"] < 5.0 or ch_info["loss_pct"] >= 90.0 or t_est_total > 300.0:
                        winner_id = self._execute_second_price_auction(uav, sim_time)
                        if winner_id is not None:
                            # Evaluate real 802.11ax A2A Mesh propagation
                            mesh_eval = A2AMeshChannel.evaluate_mesh_link(uav.pos, self.uavs[winner_id].pos, payload_bytes)
                            if not mesh_eval["in_range"] or mesh_eval["rate_mbps"] <= 0:
                                # Out of range (>350m) or outage: drop relay attempt and fallback to local onboard inference
                                cut = "full"
                                dtype = "fp32"
                                relayed_via = None
                            else:
                                relayed_via = winner_id
                                t_mesh_ms = mesh_eval["t_mesh_ms"]
                                per_mesh = mesh_eval["per"]
                                uav.tasks_relayed_out += 1
                                self.uavs[winner_id].tasks_relayed_in += 1
                                self.relayed_tasks_count += 1
                                alloc_bw = bw_allocated[winner_id]

                # Process Task Execution
                is_l1_guard = (self.fidelity == "L1" and self.fixed_cut is not None)
                cut_k = "22" if cut == "full" else cut.replace("k", "")
                c_cost = self.compute_costs.get(cut_k, self.compute_costs.get("4", {}))

                if cut == "full":
                    # Pure Onboard Edge Execution
                    t_edge_ms = 180.0 if not is_l1_guard else c_cost.get("edge_ms", 7.32) * HARDWARE_SCALE_FACTOR
                    t_tx_ms = 0.0
                    t_cloud_ms = 0.0
                    t_e2e_ms = t_edge_ms
                    energy_mj = 11.233 * t_edge_ms
                    delivered = True
                    drop_reason = "none"
                else:
                    # Split Offloading
                    if is_l1_guard:
                        t_edge_ms = (c_cost.get("edge_ms", 2.38) * HARDWARE_SCALE_FACTOR) + c_cost.get("quant_ms", 0.71)
                        t_cloud_ms = c_cost.get("cloud_ms", 8.18) + c_cost.get("nms_ms", 1.48)
                    else:
                        flop_pct = 21.38 if cut == "k4" else (43.66 if cut == "k9" else 50.0)
                        quant_overhead = 0.28 if cut == "k4" else 0.52
                        t_edge_ms = 180.0 * (flop_pct / 100.0) + quant_overhead
                        t_cloud_ms = 5.0 if cut == "k4" else 3.6
                    
                    t_ser_ms = 0.15

                    if is_l1_guard:
                        # Baseline unconstrained 3GPP trace replay mode for L1 empirical validation guard
                        active_uav = uav
                        sim_ch = {
                            "bandwidth_mbps": alloc_bw,
                            "delay_ms": ch_info["delay_ms"],
                            "packet_loss_pct": ch_info["loss_pct"],
                        }
                        net_res = active_uav.shaper.emulate_packet_transmission(payload_bytes, sim_ch, deadline_ms=None)
                        if net_res["delivered"]:
                            delivered = True
                            drop_reason = "none"
                            t_tx_ms = net_res["t_total_net_ms"]
                            t_e2e_ms = (t_edge_ms + t_ser_ms) + t_tx_ms + t_cloud_ms
                            energy_mj = 11.233 * (t_edge_ms + t_ser_ms) + 3.80 * t_tx_ms
                        else:
                            delivered = False
                            drop_reason = net_res["drop_reason"]
                            t_tx_ms = 0.0
                            t_e2e_ms = 0.0
                            energy_mj = 11.233 * (t_edge_ms + t_ser_ms)

                    elif relayed_via is not None:
                        # --- Task 4.1: Relayed transmission via A2AMeshChannel + Relay Cellular Uplink ---
                        # Step A: Stochastic packet error on A2A mesh link
                        if random.random() < per_mesh:
                            # Frame transmitted over mesh radio and lost in transit
                            delivered = False
                            drop_reason = "mesh_packet_loss"
                            t_tx_ms = t_mesh_ms
                            t_e2e_ms = 0.0
                            energy_mj = 11.233 * (t_edge_ms + t_ser_ms) + 3.80 * t_tx_ms
                        else:
                            # Mesh succeeded: Relay UAV (node j) receives and serializes to cellular
                            relay_uav = self.uavs[relayed_via]
                            ch_relay = ch_states[relayed_via]
                            packet_relay_arrival = sim_time + ((t_edge_ms + t_ser_ms + t_mesh_ms) / 1000.0)
                            
                            tx_start = max(packet_relay_arrival, relay_uav.next_available_tx_time)
                            t_queue_relay_ms = (tx_start - packet_relay_arrival) * 1000.0
                            
                            d_wire_bits = payload_bytes * 8.0
                            if alloc_bw <= 1e-4:
                                tx_duration_relay_s = 5.0
                            else:
                                tx_duration_relay_s = d_wire_bits / (alloc_bw * 1e6)
                            tx_duration_relay_ms = tx_duration_relay_s * 1000.0
                            prop_delay_relay_ms = ch_relay["delay_ms"]
                            
                            t_cellular_relay = t_queue_relay_ms + tx_duration_relay_ms + prop_delay_relay_ms
                            t_net = t_mesh_ms + t_cellular_relay
                            t_e2e_ms = (t_edge_ms + t_ser_ms) + t_net + t_cloud_ms

                            if t_e2e_ms > 300.0:
                                delivered = False
                                drop_reason = "deadline_exceeded_stale"
                                uav.stale_frames_dropped += 1
                                t_tx_ms = t_mesh_ms
                                t_e2e_ms = 0.0
                                energy_mj = 11.233 * (t_edge_ms + t_ser_ms) + 3.80 * t_tx_ms
                            elif alloc_bw <= 1e-4 or ch_relay["loss_pct"] >= 99.9:
                                delivered = False
                                drop_reason = "channel_blackout"
                                t_tx_ms = t_mesh_ms
                                t_e2e_ms = 0.0
                                energy_mj = 11.233 * (t_edge_ms + t_ser_ms) + 3.80 * t_tx_ms
                            else:
                                # Relay UAV transmits on cellular channel
                                relay_uav.next_available_tx_time = tx_start + tx_duration_relay_s
                                loss_rate = ch_relay["loss_pct"]
                                if loss_rate > 0.0 and (random.random() * 100.0) < loss_rate:
                                    delivered = False
                                    drop_reason = "cellular_packet_loss"
                                    t_tx_ms = t_net
                                    t_e2e_ms = 0.0
                                    energy_mj = 11.233 * (t_edge_ms + t_ser_ms) + 3.80 * t_tx_ms
                                else:
                                    delivered = True
                                    drop_reason = "none"
                                    t_tx_ms = t_net
                                    energy_mj = 11.233 * (t_edge_ms + t_ser_ms) + 3.80 * t_tx_ms

                    else:
                        # --- Direct cellular transmission ---
                        active_uav = uav
                        packet_arrival_time = sim_time + ((t_edge_ms + t_ser_ms) / 1000.0)
                        
                        tx_start = max(packet_arrival_time, active_uav.next_available_tx_time)
                        t_queue_s = tx_start - packet_arrival_time
                        t_queue_ms = t_queue_s * 1000.0
                        
                        d_wire_bits = payload_bytes * 8.0
                        if alloc_bw <= 1e-4:
                            tx_duration_s = 5.0
                        else:
                            tx_duration_s = d_wire_bits / (alloc_bw * 1e6)
                        tx_duration_ms = tx_duration_s * 1000.0
                        
                        prop_delay_ms = ch_info["delay_ms"]
                        t_e2e_ms = (t_edge_ms + t_ser_ms) + t_queue_ms + tx_duration_ms + prop_delay_ms + t_cloud_ms
                        
                        if t_e2e_ms > 300.0:
                            delivered = False
                            drop_reason = "deadline_exceeded_stale"
                            uav.stale_frames_dropped += 1
                            t_tx_ms = 0.0
                            t_e2e_ms = 0.0
                            energy_mj = 11.233 * (t_edge_ms + t_ser_ms)
                        elif alloc_bw <= 1e-4 or ch_info["loss_pct"] >= 99.9:
                            delivered = False
                            drop_reason = "channel_blackout"
                            t_tx_ms = 0.0
                            t_e2e_ms = 0.0
                            energy_mj = 11.233 * (t_edge_ms + t_ser_ms)
                        else:
                            active_uav.next_available_tx_time = tx_start + tx_duration_s
                            loss_rate = ch_info["loss_pct"]
                            if loss_rate > 0.0 and (random.random() * 100.0) < loss_rate:
                                delivered = False
                                drop_reason = "packet_loss"
                                t_tx_ms = tx_duration_ms + prop_delay_ms
                                t_e2e_ms = 0.0
                                energy_mj = 11.233 * (t_edge_ms + t_ser_ms) + 3.80 * t_tx_ms
                            else:
                                delivered = True
                                drop_reason = "none"
                                t_tx_ms = tx_duration_ms + prop_delay_ms
                                energy_mj = 11.233 * (t_edge_ms + t_ser_ms) + 3.80 * t_tx_ms

                # Accuracy
                cut_num = 22 if cut == "full" else int(cut.replace("k", ""))
                matching_map = next((m for m in self.map_table if m["cut_layer"] == cut_num and m["dtype"] == dtype), None)
                map_val = matching_map["map_50"] if matching_map else 0.7594

                task = PerceptionTask(
                    task_id=global_task_counter,
                    uav_id=uav.uav_id,
                    created_at_s=sim_time,
                    split_cut=cut,
                    dtype=dtype,
                    payload_bytes=payload_bytes,
                    t_edge_ms=round(t_edge_ms, 2),
                    t_tx_ms=round(t_tx_ms, 2),
                    t_cloud_ms=round(t_cloud_ms, 2),
                    t_e2e_ms=round(t_e2e_ms, 2),
                    energy_mj=round(energy_mj, 2),
                    map_50=round(map_val, 4),
                    relayed_via=relayed_via,
                    delivered=delivered,
                    dropped=(not delivered),
                    drop_reason=drop_reason,
                    completed_at_s=sim_time + (t_e2e_ms / 1000.0),
                )

                if delivered:
                    uav.tasks_delivered += 1
                else:
                    uav.tasks_dropped += 1

                # Task 4.2: Comprehensive Energy Accounting (Include Dropped & Stale Frames)
                uav.total_energy_mj += energy_mj

                self.completed_tasks.append(task)

            # Advance simulation clock
            sim_time += dt_step

        summary = self._compile_summary()
        return summary

    def _compile_summary(self) -> Dict[str, Any]:
        """Compiles detailed statistics across all completed tasks and UAVs."""
        delivered_tasks = [t for t in self.completed_tasks if t.delivered]
        dropped_tasks = [t for t in self.completed_tasks if t.dropped]
        relayed_tasks = [t for t in self.completed_tasks if t.relayed_via is not None and t.delivered]

        total_gen = len(self.completed_tasks)
        total_del = len(delivered_tasks)
        total_drop = len(dropped_tasks)
        total_stale_dropped = sum(u.stale_frames_dropped for u in self.uavs)

        deliv_rate = (total_del / max(total_gen, 1)) * 100.0
        e2e_latencies = [t.t_e2e_ms for t in delivered_tasks] if delivered_tasks else [0.0]
        tx_latencies = [t.t_tx_ms for t in delivered_tasks] if delivered_tasks else [0.0]
        # Task 4.2: Mean energy evaluated across all generated tasks without bias
        energies = [t.energy_mj for t in self.completed_tasks] if self.completed_tasks else [0.0]

        mean_e2e = float(np.mean(e2e_latencies))
        p50_e2e = float(np.percentile(e2e_latencies, 50))
        p95_e2e = float(np.percentile(e2e_latencies, 95))
        p99_e2e = float(np.percentile(e2e_latencies, 99))
        
        # Compute true empirical percentiles strictly on delivered latencies
        assert p95_e2e >= p50_e2e, f"Statistical invariant violated: P95 ({p95_e2e}) < P50 ({p50_e2e})"

        mean_tx = float(np.mean(tx_latencies))
        mean_energy = float(np.mean(energies))

        summary = {
            "fidelity": self.fidelity,
            "num_uavs": self.num_uavs,
            "duration_s": self.duration_s,
            "cell_capacity_mbps": self.cell_capacity_mbps,
            "mobility_model": self.mobility_model,
            "total_tasks_generated": total_gen,
            "total_tasks_delivered": total_del,
            "total_tasks_dropped": total_drop,
            "total_tasks_relayed": len(relayed_tasks) if len(relayed_tasks) > 0 else self.relayed_tasks_count,
            "stale_frames_dropped": total_stale_dropped,
            "effective_delivery_rate": round(deliv_rate, 2),
            "delivery_rate_pct": round(deliv_rate, 2),
            "mean_e2e_ms": round(mean_e2e, 2),
            "p50_e2e_ms": round(p50_e2e, 2),
            "p95_e2e_ms": round(p95_e2e, 2),
            "p99_e2e_ms": round(p99_e2e, 2),
            "mean_tx_ms": round(mean_tx, 2),
            "mean_energy_mj": round(mean_energy, 2),
            "uav_stats": [
                {
                    "uav_id": u.uav_id,
                    "generated": u.tasks_generated,
                    "delivered": u.tasks_delivered,
                    "dropped": u.tasks_dropped,
                    "stale_dropped": u.stale_frames_dropped,
                    "relayed_out": u.tasks_relayed_out,
                    "relayed_in": u.tasks_relayed_in,
                    "total_energy_mj": round(u.total_energy_mj, 2),
                }
                for u in self.uavs
            ]
        }
        return summary
