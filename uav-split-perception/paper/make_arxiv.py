#!/usr/bin/env python3
"""Builds the arXiv source package: paper/arxiv/ and paper/arxiv.zip (both git-ignored).

Run after `bash build_paper.sh` (it needs the generated main.bbl, because arXiv does not run BibTeX reliably).
The package holds main.tex (comments removed), main.bbl, the generated_tables/*.tex files main.tex inputs and the
figures it includes -- nothing else. It refuses to build if main.tex refers to an absolute path or if a file it
needs is missing. Check the result with pdflatex alone (twice) in a fresh copy of the folder.
"""
import re
import shutil
import sys
import zipfile
from pathlib import Path

PAPER = Path(__file__).resolve().parent
OUT = PAPER / "arxiv"


def strip_comments(tex: str) -> str:
    """Remove LaTeX comments (unescaped % to end of line); drop lines that were only a comment."""
    out = []
    for line in tex.splitlines():
        m = re.search(r"(?<!\\)%", line)
        if m is None:
            out.append(line)
        elif line[:m.start()].strip():
            out.append(line[:m.start()].rstrip())
    return "\n".join(out) + "\n"


def main() -> int:
    tex = (PAPER / "main.tex").read_text(encoding="utf-8")
    bbl = PAPER / "main.bbl"
    if not bbl.exists():
        sys.exit("main.bbl missing: run `bash build_paper.sh` first")
    clean = strip_comments(tex)
    inputs = re.findall(r"\\input\{([^}]+)\}", clean)
    graphics = re.findall(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}", clean)
    paths = inputs + [f"figures/{g}" for g in graphics]
    bad = [p for p in paths if p.startswith(("/", "\\")) or re.match(r"^[A-Za-z]:", p) or ".." in p]
    if bad:
        sys.exit(f"absolute or parent paths in main.tex: {bad}")
    missing = [p for p in paths if not (PAPER / p).exists()]
    if missing:
        sys.exit(f"missing files: {missing}")
    if OUT.exists():
        shutil.rmtree(OUT)
    (OUT / "generated_tables").mkdir(parents=True)
    (OUT / "figures").mkdir()
    (OUT / "main.tex").write_text(clean, encoding="utf-8")
    shutil.copy2(bbl, OUT / "main.bbl")
    for p in paths:
        shutil.copy2(PAPER / p, OUT / p)
    zpath = PAPER / "arxiv.zip"
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(OUT.rglob("*")):
            if f.is_file():
                z.write(f, f.relative_to(OUT).as_posix())
    files = sorted(f.relative_to(OUT).as_posix() for f in OUT.rglob("*") if f.is_file())
    print(f"{len(files)} files in {OUT.name}/ and {zpath.name}:")
    print("\n".join(f"  {f}" for f in files))
    write_metadata(clean)            # written after the zip: metadata.md is for the upload form, not the package
    return 0


def plain(text: str, macros: dict) -> str:
    """LaTeX -> plain text for the arXiv form: number macros expanded, math and spacing commands removed."""
    text = re.sub(r"\\([A-Za-z]+)\{\}", lambda m: macros.get(m.group(1), m.group(0)), text)
    text = re.sub(r"\\([A-Za-z]+)", lambda m: macros.get(m.group(1), m.group(0)), text)
    for a, b in (("$\\times$", "x"), ("$-$", "-"), ("\\,", ""), ("\\%", "%"), ("{,}", ","), ("~", " "),
                 ("--", "-"), ("\\\\", " "), ("$", "")):
        text = text.replace(a, b)
    text = re.sub(r"\{([^{}]*)\}", r"\1", text)
    return re.sub(r"\s+", " ", text).strip()


def write_metadata(tex: str) -> None:
    macros = {}
    for f in (PAPER / "generated_tables").glob("*metrics.tex"):
        macros.update(re.findall(r"\\newcommand\{\\([A-Za-z]+)\}\{(.*)\}", f.read_text(encoding="utf-8")))
    title = plain(re.search(r"\\title\{(.*?)\}\n", tex, re.S).group(1), macros)
    abstract = plain(re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", tex, re.S).group(1), macros)
    log = (PAPER / "main.log").read_text(encoding="utf-8", errors="replace")
    pages = re.search(r"Output written on main\.pdf \((\d+) pages", log).group(1)
    n_fig = len(re.findall(r"\\begin\{figure\*?\}", tex))
    n_tab = len(re.findall(r"\\begin\{table\*?\}", tex))
    leftover = re.findall(r"\\[A-Za-z]+", abstract)
    assert not leftover, f"unexpanded LaTeX in the abstract: {leftover}"
    (OUT / "metadata.md").write_text(f"""# arXiv submission metadata (not part of the source package)

Generated by `paper/make_arxiv.py` from `main.tex` and the generated macros; regenerate after any change.

**Title**

{title}

**Authors**

TO BE SUPPLIED (the paper currently reads "Author names withheld (to be supplied)").

**Abstract** (plain text, {len(abstract.split())} words, numbers written out)

{abstract}

**Primary category:** cs.NI (Networking and Internet Architecture)

**Cross-lists:** cs.CV, cs.LG, cs.RO

**Comments:** {pages} pages, {n_fig} figures, {n_tab} tables; code and data: REPO-URL

**License:** CC BY 4.0 (placeholder: to be confirmed before upload)

**Before upload:** replace the author placeholder and REPO-URL in `main.tex` (and here), rebuild with
`bash build_paper.sh`, rerun `python make_arxiv.py`, and compile `arxiv/` once more with pdflatex alone.
""", encoding="utf-8")
    print(f"metadata.md: {pages} pages, {n_fig} figures, {n_tab} tables, abstract {len(abstract.split())} words")


if __name__ == "__main__":
    sys.exit(main())
